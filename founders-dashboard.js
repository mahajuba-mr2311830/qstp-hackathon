function buildMetricCardsHtml(metrics) {
  return `
    <div class="preview-metric-cards">
      ${metrics.map(metric => `
        <div class="preview-metric-card">
          <span>${metric.label}</span>
          <strong>${metric.value}</strong>
        </div>
      `).join("")}
    </div>
  `;
}

function buildChartHtml(metrics) {
  const numericMetrics = metrics.map((item) => ({
    ...item,
    width: item.numeric > 0 ? Math.min(Math.max(item.numeric, 10), 100) : 25
  }));

  return `
    <div class="preview-chart">
      ${numericMetrics.map(metric => `
        <div class="chart-row">
          <div class="chart-row-header">
            <span>${metric.label}</span>
            <span>${metric.value}</span>
          </div>
          <div class="chart-bar-wrap">
            <div class="chart-bar" style="width: ${metric.width}%;"></div>
          </div>
        </div>
      `).join("")}
    </div>
  `;
}

