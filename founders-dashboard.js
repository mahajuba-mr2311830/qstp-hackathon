function getSelectedKpis() {
  const selected = [];

  document.querySelectorAll(".kpi-card-selector input:checked").forEach((checkbox) => {
    if (checkbox.value === "Other") {
      const customKpi = otherKpiInput.value.trim();
      if (customKpi) {
        selected.push({ name: customKpi, frequency: "Custom" });
      }
    } else {
      selected.push({
        name: checkbox.value,
        frequency: checkbox.dataset.frequency
      });
    }
  });

  return selected;
}

