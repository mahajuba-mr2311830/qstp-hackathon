function normaliseMetricKey(text) {
  return text.toLowerCase().replace(/[^a-z0-9]/g, "");
}

function findSubmittedKpi(keywords) {
  return submittedKpiEntries.find((entry) => {
    const name = normaliseMetricKey(entry.name);
    return keywords.some((keyword) => name.includes(normaliseMetricKey(keyword)));
  });
}

function extractNumber(value) {
  if (!value) return 0;
  const match = String(value).replace(/,/g, "").match(/-?\d+(\.\d+)?/);
  return match ? Number(match[0]) : 0;
}

function collectPitchDeckKpiData() {
  const revenueEntry = findSubmittedKpi(["revenue"]);
  const userGrowthEntry = findSubmittedKpi(["user growth", "growth", "users"]);
  const customerRetentionEntry = findSubmittedKpi(["customer retention", "retention"]);
  const partnershipsEntry = findSubmittedKpi(["partnership"]);
  const pocsConvertedEntry = findSubmittedKpi(["pocs converted", "poc converted", "converted"]);
  const pocsSignedEntry = findSubmittedKpi(["pocs signed", "poc signed"]);
  const fundingRaisedEntry = findSubmittedKpi(["funding raised", "funding"]);

  const revenue = quickKpiData?.revenue || revenueEntry?.value || "Not provided";
  const pocsConverted = quickKpiData?.pocConverted || pocsConvertedEntry?.value || "Not provided";
  const newHiring = quickKpiData?.newHiring || findSubmittedKpi(["headcount", "new hiring", "hiring"])?.value || "Not provided";
  const userGrowth = userGrowthEntry?.value || "Not provided";
  const customerRetention = customerRetentionEntry?.value || "Not provided";
  const partnerships = partnershipsEntry?.value || quickKpiData?.other || "Not provided";
  const fundingRaised = fundingRaisedEntry?.value || "Not provided";
  const pocsSigned = pocsSignedEntry?.value || "Not provided";

  const metrics = [
    { label: "Revenue", value: revenue, numeric: extractNumber(revenue) },
    { label: "User Growth", value: userGrowth, numeric: extractNumber(userGrowth) },
    { label: "Customer Retention", value: customerRetention, numeric: extractNumber(customerRetention) },
    { label: "Partnerships", value: partnerships, numeric: extractNumber(partnerships) },
    { label: "POCs Converted", value: pocsConverted, numeric: extractNumber(pocsConverted) },
    { label: "Funding Raised", value: fundingRaised, numeric: extractNumber(fundingRaised) }
  ];

  const insightLines = [];
  if (revenue !== "Not provided") insightLines.push(`Revenue update has been provided (${revenue}).`);
  if (fundingRaised !== "Not provided") insightLines.push(`Funding raised data indicates financing progress (${fundingRaised}).`);
  if (pocsConverted !== "Not provided") insightLines.push(`POCs converted reflects commercial traction (${pocsConverted}).`);
  if (partnerships !== "Not provided") insightLines.push(`Partnership activity supports market validation (${partnerships}).`);
  if (newHiring !== "Not provided") insightLines.push(`New hiring suggests organisational growth (${newHiring}).`);
  if (pocsSigned !== "Not provided") insightLines.push(`POCs signed indicates active pipeline development (${pocsSigned}).`);

  return {
    metrics,
    insightText: insightLines.length
      ? insightLines.join(" ")
      : "Connect KPI Forms or Quick KPI Entry to generate richer investor-ready KPI insights automatically."
  };
}

function syncKpiSlide() {
  const kpiSlide = pitchSlides.find((slide) => slide.id === "kpi-dashboard");
  if (!kpiSlide) return;

  const kpiData = collectPitchDeckKpiData();
  kpiSlide.content = `This KPI dashboard is synced automatically from founder KPI submissions.\n\n${kpiData.insightText}`;
  kpiSlide.kpiMetrics = kpiData.metrics;
  savePitchSlides();

  const anySyncedData =
    !!quickKpiData ||
    (Array.isArray(submittedKpiEntries) && submittedKpiEntries.length > 0);

  kpiSyncBadge.style.visibility = anySyncedData ? "visible" : "hidden";
}

